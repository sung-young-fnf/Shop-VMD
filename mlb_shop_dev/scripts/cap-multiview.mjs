import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { createCap } from '../src/products/caps/index.ts';
import { awaitProductTextures } from '../src/products/loading.ts';

const parameters = new URLSearchParams(location.search);
const view = parameters.get('view') ?? 'front';
const angles = { front: [0, .14], side: [1.44, .06], oppositeSide: [-1.44, .06], oblique: [.64, .23], rear: [Math.PI, .18], top: [0, 1.5], underside: [Math.PI, -1.2], interiorDetail: [Math.PI - .65, -1.0] };
if (!Object.hasOwn(angles, view)) throw new Error(`Unknown view ${view}`);
const [azimuth, elevation] = angles[view];
const cap = createCap(0);
const scene = new THREE.Scene();
scene.background = new THREE.Color('#ffffff');
scene.add(cap, new THREE.HemisphereLight('#ffffff', '#a4a2a0', 2.6));
const key = new THREE.DirectionalLight('#ffffff', 3.4);
key.position.set(-2, 4, 5); scene.add(key);
const target = new THREE.Vector3(0, .082, .015);
const distance = view === 'top' || view === 'underside' || view === 'interiorDetail' ? 2.5 : 2;
const camera = new THREE.PerspectiveCamera(10, innerWidth / innerHeight, .001, 100);
camera.position.copy(target).add(new THREE.Vector3(Math.sin(azimuth) * Math.cos(elevation), Math.sin(elevation), Math.cos(azimuth) * Math.cos(elevation)).multiplyScalar(distance));
camera.lookAt(target);
const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setPixelRatio(1); renderer.setSize(innerWidth, innerHeight);
renderer.outputColorSpace = THREE.SRGBColorSpace;
renderer.toneMapping = THREE.ACESFilmicToneMapping;
document.body.append(renderer.domElement);
await awaitProductTextures();
await renderer.compileAsync(scene, camera);
const controls = new OrbitControls(camera, renderer.domElement);
controls.target.copy(target); controls.update();
controls.addEventListener('change', () => renderer.render(scene, camera));
renderer.render(scene, camera);
await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
renderer.render(scene, camera);
window.__CAP_HIT__ = (x, y) => {
  const ray = new THREE.Raycaster();
  ray.setFromCamera(new THREE.Vector2(x / innerWidth * 2 - 1, 1 - y / innerHeight * 2), camera);
  return ray.intersectObject(cap, true).map(hit => ({ name: hit.object.name, point: hit.point.toArray(), distance: hit.distance }));
};
window.__CAP_COMPARISON__ = { ready: true, view, camera: { position: camera.position.toArray(), target: target.toArray(), fov: camera.fov, azimuth, elevation, distance }, stats: { ...renderer.info.render }, bounds: new THREE.Box3().setFromObject(cap) };
