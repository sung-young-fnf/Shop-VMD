import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { createCabinetWalls } from '../src/wall-fixtures/cabinets.ts';
import { createApparelWalls } from '../src/wall-fixtures/apparel.ts';
import { createIslands } from '../src/central-fixtures/islands.ts';
import { createFurniture } from '../src/central-fixtures/furniture.ts';
import { batchFixture } from '../src/wall-fixtures/surfaces.ts';
import { mergeFixture } from '../src/central-fixtures/parts.ts';
import { awaitProductTextures } from '../src/products/loading.ts';

const params = new URLSearchParams(location.search);
const kind = params.get('fixture') ?? 'cabinet';
const id = params.get('id') ?? { cabinet: 'ca-06', pegboard: 'w04-perforated-01', island: 'hg-e', showcase: 'showcase' }[kind];
if (!id) throw new Error(`Unknown cap fixture ${kind}`);
const root = kind === 'cabinet' ? createCabinetWalls() : kind === 'pegboard' ? createApparelWalls() : new THREE.Group();
if (kind === 'island') root.add(...createIslands());
if (kind === 'showcase') root.add(...createFurniture());
let fixture;
root.traverse(object => { if (object.userData.fixtureId === id) fixture = object; });
if (!fixture) throw new Error(`Missing actual fixture ${id}`);
fixture.removeFromParent(); fixture.position.set(0,0,0); fixture.rotation.set(0,0,0); fixture.updateMatrixWorld(true);
const caps = [];
fixture.traverse(object => { if (object.name.startsWith('reference-cap-')) caps.push({ sku: object.userData.productId, bounds: new THREE.Box3().setFromObject(object), matrix: object.matrixWorld.toArray() }); });
const fullBounds = new THREE.Box3().setFromObject(fixture);
const focus = params.get('detail') === '1' ? caps.find(cap => cap.sku === (params.get('sku') ?? 'M21N3ACP7701N'))?.bounds : fullBounds;
if (!focus) throw new Error('Fixture has no requested cap');
if (kind === 'cabinet' || kind === 'pegboard') batchFixture(fixture); else mergeFixture(fixture);
const scene = new THREE.Scene(); scene.background = new THREE.Color('#eceef0');
scene.add(fixture, new THREE.HemisphereLight('#ffffff', '#a4a2a0', 2.6));
const light = new THREE.DirectionalLight('#ffffff', 3.4); light.position.set(-2,4,5); scene.add(light);
const target = focus.getCenter(new THREE.Vector3());
const size = focus.getSize(new THREE.Vector3());
const camera = new THREE.PerspectiveCamera(35, innerWidth / innerHeight, .005, 100);
const distance = Math.max(size.y, size.x / camera.aspect, size.z) / (2 * Math.tan(THREE.MathUtils.degToRad(camera.fov / 2))) * 1.4;
const direction = params.get('view') === 'side' ? new THREE.Vector3(1,.22,.22) : params.get('view') === 'front' ? new THREE.Vector3(0,.14,1) : new THREE.Vector3(.4,.45,1);
camera.position.copy(target).add(direction.normalize().multiplyScalar(distance)); camera.lookAt(target);
const renderer = new THREE.WebGLRenderer({ antialias:true, preserveDrawingBuffer:true });
renderer.setPixelRatio(1); renderer.setSize(innerWidth,innerHeight); renderer.outputColorSpace = THREE.SRGBColorSpace; renderer.toneMapping = THREE.ACESFilmicToneMapping;
document.body.append(renderer.domElement);
const controls = new OrbitControls(camera, renderer.domElement); controls.target.copy(target); controls.update();
await awaitProductTextures(); await renderer.compileAsync(scene,camera);
const draw = () => renderer.render(scene,camera);
controls.addEventListener('change',draw); draw();
window.addEventListener('resize',() => { camera.aspect=innerWidth/innerHeight; camera.updateProjectionMatrix(); renderer.setSize(innerWidth,innerHeight); draw(); });
document.getElementById('status').textContent = `DEV ${id} · 실제 배칭 진열대 · 모자 ${caps.length}개 · ${params.get('detail') === '1' ? '근접' : '전체'} (주변 구조 숨김 없음)`;
window.__CAP_STORE__ = { ready:true, id, kind, caps, fullBounds, camera:{ position:camera.position.toArray(), target:target.toArray(), fov:camera.fov }, stats:{...renderer.info.render} };
